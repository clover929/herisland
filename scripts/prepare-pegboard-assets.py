"""Package generated transparent originals; do not invent or redraw missing assets."""
from pathlib import Path
from PIL import Image
import json
import hashlib
root=Path(__file__).resolve().parents[1]
folder=root/'public/pegboard/items'
ready=[]
report=[]
originals=root/'artifacts/pegboard-originals'
sources={p.stem:p for p in originals.glob('*.png')}
sources.update({p.stem:p for p in folder.glob('*.png')})
for source in sorted(sources.values()):
    im=Image.open(source).convert('RGBA')
    alpha=im.getchannel('A')
    if alpha.getextrema()[0]>=250:
        raise ValueError(f'{source.name}: opaque background')
    bbox=alpha.point(lambda p:255 if p>24 else 0).getbbox()
    if not bbox:raise ValueError(f'{source.name}: empty artwork')
    # Trim transparent padding while retaining a thin safety margin.
    left,top,right,bottom=bbox
    pad=12
    im=im.crop((max(0,left-pad),max(0,top-pad),min(im.width,right+pad),min(im.height,bottom+pad)))
    large=im.copy()
    large.thumbnail((1536,2304),Image.Resampling.LANCZOS)
    large.save(folder/(source.stem+'.large.webp'),'WEBP',quality=93,method=4)
    im.thumbnail((512,768),Image.Resampling.LANCZOS)
    im.save((folder/(source.stem+'.webp')),'WEBP',quality=90,method=4)
    solid=im.getchannel('A').point(lambda p:255 if p>160 else 0)
    solid_box=solid.getbbox()
    if solid_box:
        lx,ty,rx,by=solid_box
        band=solid.crop((0,ty,im.width,min(im.height,ty+max(2,int(im.height*.025)))))
        points=[(x,y) for y in range(band.height) for x in range(band.width) if band.getpixel((x,y))]
        anchor_x=sum(p[0] for p in points)/max(1,len(points))/im.width
        anchor_y=ty/im.height
    else:anchor_x=.5;anchor_y=0
    ready.append(source.stem)
    report.append({'id':source.stem,'width':im.width,'height':im.height,'anchorX':anchor_x,'anchorY':anchor_y,'transparent':True,'bytes':(folder/(source.stem+'.webp')).stat().st_size,'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest()})
(root/'src/features/pegboard/asset-manifest.ts').write_text('// Generated by scripts/prepare-pegboard-assets.py\nexport const readyAssetIds:readonly string[]='+json.dumps(ready)+';\nexport const readyAssetSizes:Record<string,{width:number;height:number;anchorX:number;anchorY:number}>='+json.dumps({r['id']:{'width':r['width'],'height':r['height'],'anchorX':r['anchorX'],'anchorY':r['anchorY']} for r in report})+';\n')
(root/'public/pegboard/asset-report.json').write_text(json.dumps(report,indent=2))
print(f'{len(ready)} independent transparent WebP assets packaged')
